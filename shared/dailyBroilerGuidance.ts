export function dailyBroilerGuidanceForCycleDay(cycleDay: number): DailyBroilerGuidance {
  const safeDay = Math.max(1, Math.floor(Number.isFinite(cycleDay) ? cycleDay : 1));
  const guidance = guidanceByAge.find((item) => safeDay >= item.from && safeDay <= item.to) ?? guidanceByAge.at(-1)!;
  const { from: _from, to: _to, ...content } = guidance;
  return { cycleDay: safeDay, ...content };
}
